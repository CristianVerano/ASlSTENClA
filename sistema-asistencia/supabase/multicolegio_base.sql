create or replace function private.usuario_puede_acceder_colegio(p_id_colegio bigint, p_roles text[] default array[]::text[])
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.perfiles p join public.roles r on r.id_rol=p.id_rol
    where p.id_usuario=(select auth.uid()) and p.activo and r.activo
      and ((r.nombre='SUPERADMIN' and (cardinality(p_roles)=0 or r.nombre=any(p_roles)))
        or (p.id_colegio=p_id_colegio and (cardinality(p_roles)=0 or r.nombre=any(p_roles))))
  );
$$;
