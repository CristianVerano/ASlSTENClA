create or replace function private.asignar_colegio_al_insertar()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_colegio bigint; v_rol text;
begin
  if (select auth.uid()) is not null then
    select p.id_colegio,r.nombre into v_colegio,v_rol
      from public.perfiles p join public.roles r on r.id_rol=p.id_rol
      where p.id_usuario=(select auth.uid()) and p.activo and r.activo;
    if v_rol is distinct from 'SUPERADMIN' then new.id_colegio := v_colegio; end if;
  end if;
  return new;
end;
$$;
revoke all on function private.asignar_colegio_al_insertar() from public,anon,authenticated;

do $$
declare t text;
begin
  foreach t in array array['asistencias','configuracion_asistencia','configuracion_sistema','dias_no_laborables','estudiantes','grados','registro_actividades','secciones'] loop
    execute format('drop trigger if exists asignar_colegio on public.%I',t);
    execute format('create trigger asignar_colegio before insert on public.%I for each row execute function private.asignar_colegio_al_insertar()',t);
  end loop;
end $$;

