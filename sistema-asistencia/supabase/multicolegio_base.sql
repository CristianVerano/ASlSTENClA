create function public.buscar_estudiante_asistencia(p_codigo text, p_colegio_slug text default 'san-pio-x-circa')
returns table (codigo text,nombres text,apellidos text,grado text,nivel text,seccion text)
language sql stable security definer set search_path = '' as $$
  select e.codigo::text,e.nombres::text,e.apellidos::text,g.nombre::text,g.nivel::text,s.nombre::text
  from public.estudiantes e join public.secciones s on s.id_colegio=e.id_colegio and s.id_seccion=e.id_seccion and s.activo
  join public.grados g on g.id_colegio=s.id_colegio and g.id_grado=s.id_grado and g.activo
  join public.colegios c on c.id_colegio=e.id_colegio and c.estado in ('ACTIVO','PRUEBA')
  where c.slug=p_colegio_slug and e.codigo=btrim(p_codigo) and e.activo limit 1
$$;

create function public.registrar_asistencia_publica(p_codigo text, p_colegio_slug text default 'san-pio-x-circa')
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_config record; v_id_colegio bigint; v_estudiante bigint; v_fecha date; v_hora time; v_dia smallint; v_estado text; v_motivo text; v_saved public.asistencias%rowtype;
begin
  if p_codigo is null or btrim(p_codigo)='' then raise exception 'Código de estudiante no válido' using errcode='22023'; end if;
  select id_colegio into v_id_colegio from public.colegios where slug=p_colegio_slug and estado in ('ACTIVO','PRUEBA');
  if v_id_colegio is null then raise exception 'Colegio no encontrado o inactivo' using errcode='P0002'; end if;
  select hora_inicio,hora_tardanza,hora_falta,dias_laborables into v_config from public.configuracion_asistencia where id_colegio=v_id_colegio and activo order by id_configuracion limit 1;
  if not found then raise exception 'No hay una configuración de asistencia activa' using errcode='P0001'; end if;
  select e.id_estudiante into v_estudiante from public.estudiantes e join public.secciones s on s.id_colegio=e.id_colegio and s.id_seccion=e.id_seccion and s.activo join public.grados g on g.id_colegio=s.id_colegio and g.id_grado=s.id_grado and g.activo where e.id_colegio=v_id_colegio and e.codigo=btrim(p_codigo) and e.activo;
  if not found then raise exception 'Estudiante no encontrado o inactivo' using errcode='P0002'; end if;
  v_fecha := (now() at time zone 'America/Lima')::date; v_hora := (now() at time zone 'America/Lima')::time; v_dia := extract(dow from v_fecha)::smallint;
  select motivo into v_motivo from public.dias_no_laborables where id_colegio=v_id_colegio and fecha=v_fecha and activo;
  if found then return jsonb_build_object('resultado','NO_LABORABLE','motivo',v_motivo,'fecha',v_fecha); end if;
  if not (v_dia=any(v_config.dias_laborables)) then return jsonb_build_object('resultado','NO_LABORABLE','motivo','Hoy no hay clases según el calendario semanal','fecha',v_fecha); end if;
  v_estado := case when v_hora>=v_config.hora_falta then 'FALTA' when v_hora>=v_config.hora_tardanza then 'TARDANZA' else 'PRESENTE' end;
  insert into public.asistencias(id_colegio,id_estudiante,fecha,hora_ingreso,estado) values(v_id_colegio,v_estudiante,v_fecha,v_hora,v_estado) on conflict(id_colegio,id_estudiante,fecha) do nothing returning * into v_saved;
  if found then return jsonb_build_object('resultado','REGISTRADO','estado',v_saved.estado,'fecha',v_saved.fecha,'hora_ingreso',v_saved.hora_ingreso); end if;
  select estado,fecha,hora_ingreso into v_saved.estado,v_saved.fecha,v_saved.hora_ingreso from public.asistencias where id_colegio=v_id_colegio and id_estudiante=v_estudiante and fecha=v_fecha;
  return jsonb_build_object('resultado','DUPLICADO','estado',v_saved.estado,'fecha',v_saved.fecha,'hora_ingreso',v_saved.hora_ingreso);
end;
$$;

create function public.obtener_identidad_publica_colegio(p_colegio_slug text default 'san-pio-x-circa')
returns jsonb language sql stable security definer set search_path = '' as $$
  select jsonb_build_object('nombre_colegio',s.nombre_colegio,'lema',s.lema,'logo_url',s.logo_url,'color_principal',s.color_principal,'color_secundario',s.color_secundario,'color_fondo',s.color_fondo,'modo',s.modo)
  from public.configuracion_sistema s join public.colegios c on c.id_colegio=s.id_colegio
  where c.slug=p_colegio_slug and c.estado in ('ACTIVO','PRUEBA') order by s.id_configuracion limit 1
$$;

